import androidx.graphics.shapes.Cubic
import androidx.graphics.shapes.Morph
import com.google.gson.GsonBuilder
import java.nio.file.Files
import java.nio.file.Path
import kotlin.math.abs
import kotlin.math.round

private fun writeOrCheck(path: Path, content: String, checking: Boolean) {
    if (checking) {
        val actual = if (Files.exists(path)) Files.readString(path) else ""
        if (actual != content) {
            val wanted = content.lines()
            val found = actual.lines()
            val first = wanted.indices.firstOrNull { it >= found.size || wanted[it] != found[it] } ?: wanted.size
            error("$path differs at line ${first + 1}; regenerate, do not edit the output.")
        }
    } else {
        Files.createDirectories(path.parent)
        Files.writeString(path, content)
    }
}

private fun svgPath(curves: List<List<Double>>): String = buildString {
    append("M${curves[0][0]} ${curves[0][1]}")
    for (c in curves) append(" C${c.drop(2).joinToString(" ")}")
    append(" Z")
}

private fun coordinates(curves: List<Cubic>): List<List<Double>> = curves.map { c ->
    listOf(c.anchor0X, c.anchor0Y, c.control0X, c.control0Y,
        c.control1X, c.control1Y, c.anchor1X, c.anchor1Y).map {
        val value = round(it.toDouble() * 1e7) / 1e7
        if (abs(value) < 1e-7) 0.0 else value
    }
}

fun main(args: Array<String>) {
    val check = args.contains("--check")
    val root = Path.of(System.getProperty("axismundi.root", "/workspace"))
    val target = root.resolve("products/wordpress/plugins/axismundi/src/apps/frontend/components/loading-indicators/assets/loading-geometry.json")
    val names = listOf("SoftBurst", "Cookie9Sided", "Pentagon", "Pill", "Sunny", "Cookie4Sided", "Oval")
    val polygons = loadingPolygons()
    val pairs = polygons.indices.map { i ->
        val next = (i + 1) % polygons.size
        val morph = Morph(polygons[i], polygons[next])
        val start = coordinates(morph.asCubics(0f))
        val end = coordinates(morph.asCubics(1f))
        check(start.size == end.size)
        // Independent interior samples validate the exported endpoint interpolation.
        for (t in listOf(0.25f, 0.5f, 0.75f)) {
            val actual = coordinates(morph.asCubics(t))
            for (j in start.indices) for (k in 0..7) {
                check(abs(actual[j][k] - (start[j][k] + (end[j][k] - start[j][k]) * t)) < 0.000002)
            }
        }
        linkedMapOf("from" to names[i], "to" to names[next], "start" to start, "end" to end)
    }
    val data = linkedMapOf(
        "generatedBy" to "tools/generators/material-shapes (Export.kt); regenerate, do not edit",
        "verifiedBy" to "tools/validators/validate_loading_geometry.py",
        "sources" to linkedMapOf("materialShapes" to "material-components-android@66b0eeb53afeb6025ffbbd37734b08e5bce197ed/MaterialShapes.java (JVM adapter)",
            "morph" to "androidx.graphics:graphics-shapes-desktop:1.1.0"),
        "precision" to 7,
        "viewBox" to listOf(0, 0, 1, 1),
        "shapes" to names.indices.map { linkedMapOf("name" to names[it], "cubics" to coordinates(polygons[it].cubics)) },
        "pairs" to pairs)
    val json = GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(data) + "\n"
    writeOrCheck(target, json, check)
    for (i in names.indices) {
        val svg = "<!-- Generated by tools/generators/material-shapes; verify using generator check mode and validate_loading_geometry.py. Apache-2.0; see LICENSE.md. -->\n" +
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 1 1\"><path fill=\"currentColor\" d=\"${svgPath(coordinates(polygons[i].cubics))}\"/></svg>\n"
        writeOrCheck(target.parent.resolve(names[i] + ".svg"), svg, check)
    }
    println("loading geometry: ${polygons.size} shapes, ${pairs.size} matched pairs, interior interpolation verified; ${if (check) "unchanged" else "generated"}")
}
